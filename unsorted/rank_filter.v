// ---------------------------------------------------------------------------
// rank_filter
//
// Конвейерный синтезируемый ранговый фильтр (order-statistic filter).
//
//  - din          : входная шина данных параметризируемой ширины WIDTH;
//  - en           : сигнал разрешения. Отсчёт защёлкивается только при en;
//  - rank_sel     : шина выбора ранга (какую порядковую статистику выдать:
//                   0 = минимум окна, LEN-1 = максимум окна);
//  - din защёлкивается в линию задержки (последовательность регистров)
//    длиной LEN, после чего конвейерно вычисляется элемент с заданным рангом.
//
// Латентность: 3 такта enable (захват -> вычисление ранга -> выборка).
//
// Ранг элемента определяется однозначно даже при равных значениях за счёт
// доразрешения по индексу позиции:
//     rank[a] = #{ b : win[b] < win[a]  ||  (win[b]==win[a] && b<a) }
// ---------------------------------------------------------------------------
module rank_filter #(
    parameter integer WIDTH = 8,                              // ширина отсчёта
    parameter integer LEN   = 8,                              // длина окна / линии задержки
    parameter integer SEL_W = (LEN <= 1) ? 1 : $clog2(LEN)    // ширина шины ранга (не переопределять)
)(
    input  wire             clk,
    input  wire             rst_n,      // асинхронный сброс, активный низкий
    input  wire             en,         // разрешение входного отсчёта
    input  wire [WIDTH-1:0] din,        // входная шина данных
    input  wire [SEL_W-1:0] rank_sel,   // выбор ранга
    output reg              dout_valid, // выходной отсчёт достоверен
    output reg  [WIDTH-1:0] dout        // элемент окна с рангом rank_sel
);

    integer i, j, k, m;

    // -----------------------------------------------------------------------
    // Ступень 1: захват входа в линию задержки (последовательность регистров)
    // -----------------------------------------------------------------------
    reg [WIDTH-1:0] win_s1 [0:LEN-1];
    reg [SEL_W-1:0] sel_s1;
    reg             vld_s1;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            vld_s1 <= 1'b0;
            sel_s1 <= {SEL_W{1'b0}};
            for (i = 0; i < LEN; i = i + 1)
                win_s1[i] <= {WIDTH{1'b0}};
        end else begin
            vld_s1 <= en;
            if (en) begin
                for (i = LEN-1; i > 0; i = i - 1)
                    win_s1[i] <= win_s1[i-1];   // сдвиг линии задержки
                win_s1[0] <= din;               // новый отсчёт
                sel_s1    <= rank_sel;          // ранг сопровождает данные по конвейеру
            end
        end
    end

    // -----------------------------------------------------------------------
    // Ступень 2: вычисление ранга каждого элемента окна
    // (для каждого a считаем, сколько элементов окна «меньше» его)
    // -----------------------------------------------------------------------
    reg [WIDTH-1:0] win_s2  [0:LEN-1];
    reg [SEL_W-1:0] rank_s2 [0:LEN-1];
    reg [SEL_W-1:0] sel_s2;
    reg             vld_s2;
    reg [SEL_W-1:0] cnt;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            vld_s2 <= 1'b0;
            sel_s2 <= {SEL_W{1'b0}};
            for (j = 0; j < LEN; j = j + 1) begin
                win_s2[j]  <= {WIDTH{1'b0}};
                rank_s2[j] <= {SEL_W{1'b0}};
            end
        end else begin
            vld_s2 <= vld_s1;
            sel_s2 <= sel_s1;
            for (j = 0; j < LEN; j = j + 1) begin
                cnt = {SEL_W{1'b0}};
                for (k = 0; k < LEN; k = k + 1) begin
                    if ( (win_s1[k] <  win_s1[j]) ||
                         ((win_s1[k] == win_s1[j]) && (k < j)) )
                        cnt = cnt + 1'b1;
                end
                rank_s2[j] <= cnt;          // ранг элемента j
                win_s2[j]  <= win_s1[j];    // снимок окна тащим дальше
            end
        end
    end

    // -----------------------------------------------------------------------
    // Ступень 3: выборка элемента, чей ранг совпал с запрошенным
    // -----------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            dout_valid <= 1'b0;
            dout       <= {WIDTH{1'b0}};
        end else begin
            dout_valid <= vld_s2;
            dout       <= {WIDTH{1'b0}};
            for (m = 0; m < LEN; m = m + 1) begin
                if (rank_s2[m] == sel_s2)
                    dout <= win_s2[m];      // ранги уникальны -> ровно одно совпадение
            end
        end
    end

endmodule
